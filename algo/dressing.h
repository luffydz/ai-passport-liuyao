#pragma once

#include <stdbool.h>

// ---------------------------------------------------------------------------
// 每日穿衣 —— 按当日【日柱】推五行穿衣色（纯计算，无 UI、无依赖）
//
// 【规则来源】民俗网站「五行穿衣每日指南」（3g.d5168.com/wuhang/，周新春易学网）。
// 该站**不公开任何公式**，只给结果。这套规则是从它输出的「日柱干支 + 30 天颜色
// 序列」反向还原出来的，并逐日回代验证（31/31 吻合）。验证见 test_dressing.c。
//
// 【四步链】
//   ① 公历日期 → 日柱干支（60 甲子，基准 2000-01-01 = 戊午，序数 54）
//   ② 以【日支】的五行为「我」—— 不是日干。这点最容易搞错，见下面说明。
//   ③ 按生克分三档：我生 = 大吉、同我 = 次吉、我克 = 不宜
//   ④ 套「五行 → 颜色」表输出
//
// 【为什么是日支不是日干】取 2026-09-14（日柱辛卯，日干辛金、日支卯木）反证：
//   若「我 = 辛金」→ 大吉该是土(生金)或金(比肩)；
//   但该站实际是 大吉=火、次吉=木、不宜=土，
//   只有「我 = 卯木」时三档才能同时成立。
//   该站自己的措辞「今日所克不宜」也印证：木克土，主语正是卯木。
//
// 【只有三档】民俗里常见的五档（大吉/次吉/平/忌/大忌）在这里被压成三档，
// 「生我」「克我」两类关系该站【略去不表】—— 这不是我们漏了，是照搬原站口径。
//
// 【「大吉」取的是日支所生】即顺生泄秀，而**不是**通常民俗「取生我者补身」的
// 思路。这是该站与部分同类站点结果不同的根本原因，照搬时有意保留。
//
// 【性质】干支与颜色对应属传统术数约定，无科学依据；原站亦自注「仅供参考」。
// ---------------------------------------------------------------------------

// 五行下标。顺序刻意取【相生链】次序：木→火→土→金→水→（回木）
// 这样「我生」= +1、「我克」= +2，两个关系都退化成加法，不会写错。
typedef enum {
    WX_MU  = 0,   // 木
    WX_HUO,       // 火
    WX_TU,        // 土
    WX_JIN,       // 金
    WX_SHUI,      // 水
    WX_COUNT
} wuxing_t;

typedef struct {
    int gan, zhi;        // 日柱天干/地支下标（甲 = 0，子 = 0）
    int zhi_wuxing;      // 日支五行 ＝ 「我」
} day_gz_t;

// 三档结论。每档是一串颜色词（沿用原站用词与顿号分隔），可直接显示。
typedef struct {
    const char *daji;    // 大吉：日支所生（我生）
    const char *ciji;    // 次吉：与日支同气（同我）
    const char *buyi;    // 不宜：日支所克（我克）
    const char *me;      // 「我」的五行名（木/火/土/金/水），便于自检与展示
} dressing_t;

// 主入口：算某一天的日柱与三档穿衣色。日期非法返回 false。
// 支持 2000 年及以后；更早的年份会被 mod 归一化，但基准外推未必准，不建议。
bool dressing_for_date(int y, int m, int d, day_gz_t *gz, dressing_t *out);

// 供显示/自检用。
const char *wuxing_name(int wuxing);   // 木 火 土 金 水
const char *gan_name(int i);           // 甲 乙 丙 …
const char *zhi_name(int i);           // 子 丑 寅 …

// 某一行的颜色词串（用于把「我生/同我/我克」换成颜色）。
const char *wuxing_colors(int wuxing);
