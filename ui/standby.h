#pragma once

#include <stdbool.h>

// ---------------------------------------------------------------------------
// 待机画面 —— 无操作一段时间后自动进入
//
// 【为什么做】本机电池只有 520mAh，背光是这块小屏上最耗电的部分。停在界面不动
// 时一直全亮是纯浪费。进待机后把背光压到 25%。在六爻 / 每日穿衣里还会换成一幅
// 静态图案（只画一次，之后不再重绘，所以几乎不耗 CPU）；功能选择页则只压暗背光、不换图。
//
// 【为什么是图案，不是时钟】本机没有 RTC、也不联网 —— 断电就不知道是几点，也没
// 法对时。所以"待机时钟"这类画面根本做不了。这里放的是一幅先天八卦环。
//
// 【用法】app_ui.c 里三处调用，顺序不能颠倒：
//     standby_init()       启动时建好图层（先藏着），并起一个空闲计时器
//     standby_note_key()   每次按键都要调 —— 重置空闲计时
//     standby_wake()       按键时【先】问它。返回 true 表示这次按键只用于唤醒，
//                          调用方必须把这次按键直接丢掉、不要再分发下去
//                          （否则从待机按 OK 会顺手把卦起了）
// ---------------------------------------------------------------------------
void standby_init(void);
void standby_note_key(void);
bool standby_wake(void);

// 待机图按当前 App 切换（六爻=八卦环，穿衣=五行色环）。
// 功能选择页传 STANDBY_APP_NONE：不盖待机图，只把背光压到 25%。
// 在 app_ui 切到对应 App / 回到启动页时调用一次即可；待机图层只画一次、之后不重绘。
typedef enum {
    STANDBY_APP_NONE = 0,     // 功能选择页：仅调暗背光，不显示待机图
    STANDBY_APP_LIUYAO,       // 六爻：先天八卦环
    STANDBY_APP_DRESSING,     // 每日穿衣：五行色环
} standby_app_t;
void standby_set_app(standby_app_t app);
