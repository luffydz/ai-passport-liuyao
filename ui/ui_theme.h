// ui/ui_theme.h —— 国风主题（黑底金线）。
//
// 与基线 ui_pixel（天空/草地/像素风）并列的另一套主题，本 App 使用这一套。
// 配色取自原 Cardputer 项目的设计稿，保证视觉延续。
//
// 【双端共用约定】本文件只依赖 lvgl.h，不含 ESP-IDF 头文件；
// 字体由平台层提供：
//   真机   → 编译进 flash 的静态字库（走 XIP，不占 RAM）
//   模拟器 → FreeType 动态加载 OTF/TTF
#pragma once

#include "lvgl.h"

// ---------------------------------------------------------------------------
// 配色（黑金）
// ---------------------------------------------------------------------------
#define TH_BG      0x000000   // 纯黑底
#define TH_FRAME   0xD4AF37   // 金色描边
#define TH_GOLD    0xFFD766   // 高亮金（选中/强调）
#define TH_TEXT    0xE8D8B0   // 正文（米金）
#define TH_DIM     0x7A6A45   // 次要文字 / 未选中
#define TH_RED     0xC0392B   // 动爻 / 警示

// ---------------------------------------------------------------------------
// 字体（平台层实现）
// ---------------------------------------------------------------------------
// 字号分五档（真机侧会按实际用到的字符集生成对应静态字库）
const lv_font_t *th_font_hero(void);    // 48px 欢迎页大标题
const lv_font_t *th_font_title(void);   // 34px 次要大字（日期/结果）
const lv_font_t *th_font_body(void);    // 18px 正文
const lv_font_t *th_font_small(void);   // 16px 底部提示条
const lv_font_t *th_font_tiny(void);    // 14px 次要说明（副标题等）

// ---------------------------------------------------------------------------
// 基础控件
// ---------------------------------------------------------------------------
// ---------------------------------------------------------------------------
// 屏幕外框：圆角金线（内缩，让开物理边框）
// ---------------------------------------------------------------------------
// 为什么不是贴边的直角线：
//   ① 贴边直角线在设备圆角处会被切掉；
//   ② 实测贴边金线会被物理边框遮住 —— 左/右/下三边至少被吃 2px，
//      只剩上沿一条露出来，看着像"框偏下"。
// 所以把金线画成一个【内缩几像素的圆角矩形】：弧线落在屏幕内部，
// 既不会被圆角切，也不容易整条被边框吃掉。
//
// 圆角半径不是拍的，来自官方产品图 docs/brand/ai-passport-front.png：
//   屏幕蓝色区宽 284px、左上角圆弧内缩 26px（该图高宽比 1.331 ≈ 真值 1.333，
//   证明量到的就是屏幕）→ 比例 0.0915 → 240px 屏宽下 ≈ 22px ≈ 3.4mm。
// 金线内缩 TH_FRAME_INSET 之后，与屏幕圆角同心的半径 ≈ 22 - TH_FRAME_INSET。
//
// 四个可调参数（改完用模拟器出图看，再烧真机确认）：
#define TH_FRAME_INSET    6   // 金线到屏幕边缘的距离(px)：太小会被物理边框吃掉
#define TH_FRAME_LINE_W   2   // 金线宽度(px)
#define TH_FRAME_DY       0   // 整圈金线的纵向偏移(px)，负 = 上移
#define TH_SCREEN_RADIUS 16   // 金线圆角半径 ≈ 22 - TH_FRAME_INSET

// 整屏：纯黑底 + 一圈内缩的圆角金线。
lv_obj_t *th_screen_create(void);

// 金色描边圆角框（默认黑底、1px 金线）—— 面板/卡片/输入格都用它
lv_obj_t *th_frame_create(lv_obj_t *parent, int x, int y, int w, int h);

// 统一风格文字
lv_obj_t *th_label(lv_obj_t *parent, const char *text,
                   const lv_font_t *font, uint32_t color);

// 选中态：金色高亮边框（未选中=暗金）
void th_set_selected(lv_obj_t *obj, bool selected);

// ---------------------------------------------------------------------------
// 文字视觉居中的垂直修正量
//
// 为什么需要：LVGL 单行 label 的盒高 = 字体 line_height，盒子居中不等于
// 「看起来居中」—— 汉字墨迹在盒内偏下（基线离盒底只有 base_line 个像素）。
// 实测 18px 思源黑体偏下 3.75px，肉眼可见。
//
// 修正量由字体度量算出（不写死像素）：对参考字符取字形盒，按
//   墨迹中心偏移 = line_height/2 - base_line - box_h/2 - ofs_y
// 得到「需要向上移动多少像素」。
//
// 用法：lv_obj_align(obj, LV_ALIGN_CENTER, 0, -th_vshift(font, '国'));
//   ref_char 取该字体下"满格"的代表字：中文用 '国'，数字用 '8'。
// ---------------------------------------------------------------------------
int th_vshift(const lv_font_t *font, uint32_t ref_char);

// 屏幕底部的操作提示条（固定贴底）
lv_obj_t *th_hint_create(lv_obj_t *parent, const char *text);
