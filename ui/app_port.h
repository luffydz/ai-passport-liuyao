// ui/app_port.h —— UI 层与硬件之间的唯一接口（平台抽象）。
//
// 【设计约定 · 必须遵守】
//   ui/ 下的所有 .c 文件：
//     ✓ 只允许 include "lvgl.h" / "ui_pixel.h" / "app_port.h" / 本目录其他头文件
//     ✗ 禁止 include esp_log.h / bsp_*.h / freertos/* 等 ESP-IDF 头文件
//   需要电量、背光、加锁时，一律调用本文件声明的函数。
//
//   真机  → 由 BSP 实现（转调 bsp_battery_* / bsp_display_backlight / bsp_lvgl_lock）
//   模拟器 → 由 sim/host/ 实现（假数据 / 无锁）
//
//   这样同一份 UI 源码可以两端直接编译，不存在"模拟器跑的不是真机代码"的漂移。
#pragma once

#include <stdbool.h>
#include <stdint.h>

// ---------------------------------------------------------------------------
// 按键语义（与真机 BSP 的 bsp_btn_t / bsp_btn_ev_t 一一对应）
// ---------------------------------------------------------------------------
typedef enum {
    APP_KEY_UP = 0,   // 上
    APP_KEY_DOWN,     // 下
    APP_KEY_OK,       // 确定
} app_key_t;

typedef enum {
    APP_KEY_CLICK = 0,  // 短按抬起
    APP_KEY_LONG,       // 长按抬起（确定键长按 = 返回上一层，由 app_ui 统一拦截）
    // 按下瞬间。「按住蓄力」这类需要按住过程反馈的交互靠它；
    // 真机对应 bsp_button.h 的 BSP_BTN_PRESS（低延迟）。
    // 追加在末尾，保持 CLICK/LONG 原有数值不变。
    APP_KEY_PRESS,
} app_key_ev_t;

// ---------------------------------------------------------------------------
// 硬件能力
// ---------------------------------------------------------------------------

// 电量百分比 0..100；读数不可用时返回 -1（UI 必须优雅降级，不要画数字）。
int app_port_battery_percent(void);

// 背光亮度 0..100(%)。真机走 LEDC PWM，模拟器只打印。
void app_port_backlight_set(int percent);

// ---------------------------------------------------------------------------
// 音频：播放一段 16bit 单声道 PCM
//
// ⚠ 硬性约定：本函数必须 **非阻塞返回**。
//   真机 → bsp_audio_write() 是阻塞的（1.3 秒的铜钱声足以卡死按键任务），
//          所以真机侧实现必须把数据丢给音频 worker 任务，绝不能直接写 I2S。
//   模拟器 → SDL 音频队列本身就是异步的。
//
// 真机如果采样率与 BSP 当前格式不同，bsp_audio_set_format() 会先 close 再
// 重新 open codec（这是 bsp_audio.h 里标注的坑），同样应在 worker 里做。
// ---------------------------------------------------------------------------
void app_port_play_pcm(const int16_t *samples, int count, int sample_rate);

// LVGL 非线程安全：非 LVGL 任务里操作 lv_* 对象前后必须加解锁。
// 真机 → bsp_lvgl_lock；模拟器（单线程）→ 直接返回 true。
bool app_port_lvgl_lock(int timeout_ms);
void app_port_lvgl_unlock(void);

// ---------------------------------------------------------------------------
// 随机数 —— 随机用
//
// 为什么不让 UI 层直接调 rand()/esp_random()：ui/ 不许 include ESP-IDF 头文件
//（见本文件顶部的约定），而且模拟器需要自己那套实现。
//   真机   → esp_random()（芯片硬件随机源）
//   模拟器 → PRNG；可用环境变量 SIM_SEED 固定种子，方便复现出图
// ---------------------------------------------------------------------------
uint32_t app_port_random(void);

// ---------------------------------------------------------------------------
// 屏幕规格（真机 ST7789P3：240x320 竖屏）
// ---------------------------------------------------------------------------
#define APP_SCREEN_W 240
#define APP_SCREEN_H 320

// ---------------------------------------------------------------------------
// 选定日期持久化
//
// 每日穿衣要用"今天是哪天"（定五行旺衰），而本设备没有 RTC 时钟源
// ——断电即丢时间，所以日期由用户输入，并且要存下来（下次开机不用重填）。
// 真机 → NVS；模拟器 → 本地文件。
// ---------------------------------------------------------------------------
void app_port_date_save(int year, int month, int day);

// 读回上次保存的日期。没有存过返回 false。
bool app_port_date_load(int *year, int *month, int *day);

// ---------------------------------------------------------------------------
// 铜钱音效响度 0..100(%)，0 = 静音
//
// 为什么做成可调：有时候需要不出声、或轻一些（深夜、哄睡、
// 图书馆、开会间隙…），而本设备没有别的静音途径。
//
//   get → 当前设定值。真机首次调用时会从 NVS 读入【并真正写进 codec】——
//         把"写入硬件"放在读入持久化值的同一步，就不会漏，也省得 UI 再显式
//         "应用"一次，开机第一声就是用户上次设定的响度。
//   set → 立即生效【并持久化】。用户特意调小的，下次开机理应保持。
//
// 真机 → bsp_audio_set_volume + NVS；模拟器 → 本地小文件（同日期那套写法）。
// ---------------------------------------------------------------------------
void app_port_volume_set(int percent);
int  app_port_volume_get(void);
