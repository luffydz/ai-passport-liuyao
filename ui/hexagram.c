const char* getLineName(uint8_t lineIdx, bool isYang) {
  static char buf[8];
  const char* yinYang = isYang ? YANG_STR : YIN_STR;
  const char* pos = LINE_POS_NAMES[lineIdx];
  // 六爻命名: 初/上 + 九/六, 中间 九/六 + 二三西五
  // 例如: 初九, 九二, 九三, 九四, 九五, 上九
  if (lineIdx == 0 || lineIdx == 5) {
    // 初爻/上爻: 爻位在前
    buf[0]=pos[0]; buf[1]=pos[1]; buf[2]=pos[2];
    buf[3]=yinYang[0]; buf[4]=yinYang[1]; buf[5]=yinYang[2];
  } else {
    // 二至五爻: 九/六在前
    buf[0]=yinYang[0]; buf[1]=yinYang[1]; buf[2]=yinYang[2];
    buf[3]=pos[0]; buf[4]=pos[1]; buf[5]=pos[2];
  }
  buf[6] = 0;
  return buf;
}

