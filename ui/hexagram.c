static int zhi_index_of(const char* z) {
  if (!z) return -1;
  for (int i = 0; i < 12; i++) if (!strcmp(GZ_ZHI[i], z)) return i;
  return -1;
}

static int wuxing_index_of(const char* w) {
  if (!w) return -1;
  for (int i = 0; i < 5; i++) if (!strcmp(GZ_WUXING[i], w)) return i;
  return -1;
}

// 六亲：以卦宫五行为"我"
//   生我者父母 / 我生者子孙 / 克我者官鬼 / 我克者妻财 / 同我者兄弟
static int liuqin_of(int palace_wx, int line_wx) {
  if (line_wx == palace_wx)           return LIUQIN_XIONGDI;   // 同我
  if ((line_wx + 1) % 5 == palace_wx) return LIUQIN_FUMU;      // 它生我
  if ((palace_wx + 1) % 5 == line_wx) return LIUQIN_ZISUN;     // 我生它
  if ((line_wx + 2) % 5 == palace_wx) return LIUQIN_GUANGUI;   // 它克我
  return LIUQIN_QICAI;                                         // 我克它
}

void getLiuyaoChart(uint8_t upper, uint8_t lower, uint8_t movingLine,
                    liuyao_chart_t* out)
{
  if (!out) return;
  memset(out, 0, sizeof(*out));
  if (upper >= 8 || lower >= 8 || movingLine >= 6) return;

  // 1) 定卦宫与宫内位次
  const uint8_t key = (uint8_t)(upper * 8 + lower);
  int palace = -1, slot = -1;
  for (int p = 0; p < 8 && palace < 0; p++) {
    for (int s = 0; s < 8; s++) {
      if (PALACE_HEX[p][s] == key) { palace = p; slot = s; break; }
    }
  }
  if (palace < 0) return;   // 理论不可达：64 卦必然落在某一宫

  out->palace        = (uint8_t)palace;
  out->palace_name   = PALACE_NAME[palace];
  out->palace_wuxing = getTrigramElement((uint8_t)palace);
  const int palace_wx = wuxing_index_of(out->palace_wuxing);

  // 2) 逐爻：纳甲 → 地支五行 → 六亲 → 阴阳 → 世应 → 动爻
  for (int i = 0; i < 6; i++) {
    const bool lower_half = (i < 3);
    const uint8_t tri = lower_half ? lower : upper;      // 该爻所属的卦
    const int     k   = lower_half ? i : (i - 3);        // 在该卦里的位次

    const char* gan = lower_half ? NAJIA_GAN_IN[tri] : NAJIA_GAN_OUT[tri];
    const char* zhi = lower_half ? NAJIA_ZHI_IN[tri][k] : NAJIA_ZHI_OUT[tri][k];

    snprintf(out->lines[i].ganzhi, sizeof(out->lines[i].ganzhi), "%s%s", gan, zhi);

    const int zi = zhi_index_of(zhi);
    const int wx = (zi >= 0) ? (int)GZ_ZHI_WUXING[zi] : 0;

    out->lines[i].wuxing    = GZ_WUXING[wx];
    out->lines[i].liuqin    = LIUQIN_NAME[liuqin_of(palace_wx, wx)];
    out->lines[i].is_yang   = TRIGRAM_LINES[tri][k] != 0;
    out->lines[i].is_moving = (i == (int)movingLine);
    out->lines[i].shiying   = (i == SHI_POS[slot])  ? 1
                            : (i == YING_POS[slot]) ? 2 : 0;
  }
}

