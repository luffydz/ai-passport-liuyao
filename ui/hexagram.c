int getYongShenLine(uint8_t catIdx, const liuyao_chart_t* chart)
{
  if (!chart || catIdx >= CATEGORY_COUNT) return -1;

  const int want = CATEGORY_YONGSHEN_QIN[catIdx];
  if (want >= 0) {
    const char* name = LIUQIN_NAME[want];
    // 同六亲可能出现多爻，取靠下（先出现）的一爻
    for (int i = 0; i < 6; i++) {
      if (chart->lines[i].liuqin && !strcmp(chart->lines[i].liuqin, name)) return i;
    }
    return -1;   // 六爻术语：用神不上卦，需另取伏神（本层未实现）
  }
  // 以世爻为用
  for (int i = 0; i < 6; i++) if (chart->lines[i].shiying == 1) return i;
  return -1;
}
