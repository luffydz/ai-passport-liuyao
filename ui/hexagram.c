// ===== 动爻所在卦的五行走向（本卦 → 变卦）=====
// 同样写短，便于拼进断语句。
// 与爻位、事由三者彼此独立 → 断语句变体 = 6 × 5 × 2 = 60（单类别，全库 480）。
static const char* ELEM_RELATION_TEXT[5] = {
  "卦象比和",      // 0 比和
  "卦生变顺势",    // 1 本卦五行生变卦五行
  "变生卦得助",    // 2 变卦五行生本卦五行
  "卦克变可制",    // 3 本卦五行克变卦五行
  "变克卦受阻",    // 4 变卦五行克本卦五行（六爻里叫"回头克"）
};

// 五行索引按【相生顺序】排：木0 → 火1 → 土2 → 金3 → 水4
// 相生：(i+1)%5    相克：(i+2)%5
static int elem_index(const char* e) {
  if (!e) return -1;
  if (!strcmp(e, "木")) return 0;
  if (!strcmp(e, "火")) return 1;
  if (!strcmp(e, "土")) return 2;
  if (!strcmp(e, "金")) return 3;
  if (!strcmp(e, "水")) return 4;
  return -1;
}

// 返回 ELEM_RELATION_TEXT 的下标：0比和 1卦生变 2变生卦 3卦克变 4变克卦
static int five_elem_relation(const char* before, const char* after) {
  const int a = elem_index(before);
  const int b = elem_index(after);
  if (a < 0 || b < 0) return 0;          // 数据异常时不崩，退回"比和"
  if (a == b) return 0;
  if ((a + 1) % 5 == b) return 1;        // 我生它 → 顺势
  if ((b + 1) % 5 == a) return 2;        // 它生我 → 得助
  if ((a + 2) % 5 == b) return 3;        // 我克它 → 可制
  return 4;                              // 它克我 → 受阻
}

const char* getLinePosMeaning(uint8_t lineIdx) {
  if (lineIdx >= 6) return "";
  return LINE_POS_MEANING[lineIdx];
}

const char* getElemRelationText(uint8_t upper, uint8_t lower, uint8_t movingLine) {
  if (movingLine >= 6 || upper >= 8 || lower >= 8) return "";
  // 动爻在 0..2 → 动的是下卦；在 3..5 → 动的是上卦
  const char* before = (movingLine < 3) ? getTrigramElement(lower)
                                        : getTrigramElement(upper);
  uint8_t cu, cl;
  getChangedHexagram(upper, lower, movingLine, &cu, &cl);
  const char* after = (movingLine < 3) ? getTrigramElement(cl)
                                       : getTrigramElement(cu);
  return ELEM_RELATION_TEXT[five_elem_relation(before, after)];
}

